"""Exploratory post-hoc analysis "native whole-image single pass on DOTA" (user 2026-11-13; framing recorded in
docs/DECISIONS.md 2026-11-13 06:22 before any number). Descriptive only: no verdict, no frozen row or setting changes.

    python scripts/dota_native_pass.py predict   # GPU (nothing else on it): N_z1 on all DOTA-val images, both models
    python scripts/dota_native_pass.py eval      # CPU (cores 16-23, nice 19): row evaluations with bootstrap vectors
    python scripts/dota_native_pass.py sizes     # CPU: AP50 / AP / recall@0.5 per size bin (incl. 128-256, >256, >128)
    python scripts/dota_native_pass.py counts    # object counts of the subsets (needs the labels) -> object_counts.json
    python scripts/dota_native_pass.py analyse   # contrasts -> runs/dota/native_pass/report.json, then report
    python scripts/dota_native_pass.py report    # report.json -> REPORT.md, reports/dota/NATIVE_PASS_EXPLORATORY.md (+ JSON)

N_z1: whole image at z = 1 (padded bottom/right with grey 114 to multiples of 32, Ultralytics predictor at exactly that
input shape, gain 1), head / post-processing / conf / limit of the frozen A_2048 row, float32, batch 1; NMS class offset
2^15 (equivalence fix, see DECISIONS). Subset F = images on which N_z1 runs without OOM.
(i) on F: N_z1, A_2048, NMS-o2m_2048 (YOLOv10s also NMS-o2o_2048), RG_2048, all restricted to F;
(ii) on all images: hybrid H (N_z1 on F, RG_2048 elsewhere) vs. RG_2048 and A_2048 (stored full-val evaluations).
"""

from __future__ import annotations

