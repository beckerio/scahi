OUT = REPO / "runs/dota/native_pass"
REP = REPO / "reports/dota"  # report copies (exploratory; regenerated by scripts/regenerate_paper.py)
MODELS = ("yolov10s", "yolo11s")
S = 2048
PAD = 114


def _frozen_row(m: str, row: str) -> tuple[dict, int]:
    from scahi.dota import final as F

    fz = F.frozen(F.FROZEN if m == "yolov10s" else F.FROZEN_NEW)
    return next(r for r in fz["rows"] if r["id"] == f"{row}_{m}_{S}"), fz["pipeline_limit"]


def predict() -> None:
    import cv2
    import torch
    from ultralytics import YOLO
    from ultralytics.utils import nms as NMS

    from scahi.dota import data as D
    from scahi.dota import evaluate as EV
    from scahi.dota import pipeline as P
    from scahi.dota import train as T
    from scahi.infer.full import BRANCH_NMS_ARG

    NMS.non_max_suppression = functools.partial(NMS.non_max_suppression, max_wh=1 << 15)  # equivalence fix (DECISIONS)
    OUT.mkdir(parents=True, exist_ok=True)
    stems = P.split_stems("val")
    for m in MODELS:
        a, lim = _frozen_row(m, "A")
        assert a["kind"] == "single" and a["imgsz"] == S
        y = YOLO(str(T.weights(m, S)))
        kw = {"conf": T.PRED_CONF, "max_det": lim, "verbose": False, "nms": BRANCH_NMS_ARG[a["branch"]]}
        shapes: list = []
        imgs = {s: D.image_path("val", s) for s in stems}
        hw = {}
        for s in stems:
            from PIL import Image

            with Image.open(imgs[s]) as im:
                hw[s] = (im.size[1], im.size[0])
        order = sorted(stems, key=lambda s: hw[s][0] * hw[s][1])
        rows, per = [], {}
        hooked = False
        for n, s in enumerate(order):
            img = cv2.imread(str(imgs[s]))
            H, W = img.shape[:2]
            Hp, Wp = -(-H // 32) * 32, -(-W // 32) * 32
            x = cv2.copyMakeBorder(img, 0, Hp - H, 0, Wp - W, cv2.BORDER_CONSTANT, value=(PAD, PAD, PAD))
            del img
            rec = {"W": W, "H": H, "input_hw": [Hp, Wp]}
            try:
                if n == 0:
                    y.predict(x, imgsz=(Hp, Wp), **kw)  # warm-up (not timed)
                if not hooked:
                    y.predictor.model.model.register_forward_pre_hook(lambda mod, inp: shapes.append(tuple(inp[0].shape[2:])))
                    hooked = True
                torch.cuda.synchronize()
                torch.cuda.reset_peak_memory_stats()
                t0 = time.perf_counter()
                r = y.predict(x, imgsz=(Hp, Wp), **kw)[0]
                torch.cuda.synchronize()
                rec["ms"] = 1000 * (time.perf_counter() - t0)
                rec["peak_mem_mb"] = torch.cuda.max_memory_allocated() / 2**20
                assert shapes[-1] == (Hp, Wp), (s, shapes[-1], (Hp, Wp))
                b = r.boxes
                xyxy = b.xyxy.cpu().numpy().astype(np.float64)
                xyxy[:, [0, 2]] = xyxy[:, [0, 2]].clip(0, W)
                xyxy[:, [1, 3]] = xyxy[:, [1, 3]].clip(0, H)
                sc, cl = b.conf.cpu().numpy(), b.cls.cpu().numpy().astype(int)
                k = sc >= a["conf"]
                rows += [(s, int(c), float(q), *map(float, bb)) for bb, q, c in zip(xyxy[k], sc[k], cl[k])]
                rec.update(fits=True, n_dets=int(k.sum()), at_limit=bool(len(sc) >= lim))
                del r, b
            except torch.cuda.OutOfMemoryError:
                rec.update(fits=False, error="CUDA out of memory")
            torch.cuda.empty_cache()
            per[s] = rec
            if n % 50 == 0 or not rec["fits"]:
                print(m, n, s, rec, flush=True)
        dets = pd.DataFrame(rows, columns=EV.DET_COLS)
        dets.to_parquet(OUT / f"N_z1_{m}.parquet")
        (OUT / f"N_z1_{m}.json").write_text(json.dumps({
            "model": m, "weights": str(T.weights(m, S).relative_to(REPO)), "A_row": a["id"], "conf": a["conf"],
            "branch": a["branch"], "pipeline_limit": lim, "dtype": "float32", "batch": 1, "nms_max_wh": 1 << 15,
            "gpu": torch.cuda.get_device_name(0), "n_dets": len(dets), "images": per}, indent=1))
        print(m, "fit", sum(v["fits"] for v in per.values()), "of", len(per), flush=True)
        del y
        torch.cuda.empty_cache()


def _subset(m: str) -> list[str]:
    from scahi.dota import pipeline as P

    per = json.loads((OUT / f"N_z1_{m}.json").read_text())["images"]
    return [s for s in P.split_stems("val") if per[s]["fits"]]


def _dets(m: str, name: str) -> pd.DataFrame:
    from scahi.dota import final as F
    from scahi.dota import pipeline as P

    if name == "N_z1":
        return pd.read_parquet(OUT / f"N_z1_{m}.parquet")
    if name == "H":
        fit = set(_subset(m))
        n = pd.read_parquet(OUT / f"N_z1_{m}.parquet")
        rg = pd.read_parquet(F.DETS_DIR / f"RG_{m}_{S}.parquet")
        assert set(P.split_stems("val")) >= fit
        return pd.concat([n[n.image.isin(fit)], rg[~rg.image.isin(fit)]], ignore_index=True)
    return pd.read_parquet(F.DETS_DIR / f"{name}_{m}_{S}.parquet")


def _eval_job(job: tuple[str, str, str]) -> str:
    """job = (model, row name, set): set 'F' (subset of the model) or 'all' (458 images)."""
    import torch

    from scahi.dota import final as F
    from scahi.dota import pipeline as P

    torch.set_num_threads(1)
    m, name, st = job
    f = OUT / "eval" / f"{name}_{m}_{st}.json"
    if f.exists():
        return f.stem
    d = _dets(m, name)
    if st == "F":
        sub = _subset(m)
        d = d[d.image.isin(set(sub))]
        with mock.patch.object(P, "split_stems", lambda split: list(sub)):
            o, v = F.evaluate_row(f"{name}_{m}_{st}", "val", dets=d.reset_index(drop=True))
        o["n_images"] = len(sub)
    else:
        o, v = F.evaluate_row(f"{name}_{m}_{st}", "val", dets=d.reset_index(drop=True))
        o["n_images"] = len(P.split_stems("val"))
    np.savez(OUT / "eval" / f"{f.stem}_boot.npz", **v)
    f.write_text(json.dumps(o, indent=1))
    return f.stem


def jobs() -> list[tuple[str, str, str]]:
    out = []
    for m in MODELS:
        for name in ["N_z1", "A", "NMS-o2m", "RG"] + (["NMS-o2o"] if m == "yolov10s" else []):
            out.append((m, name, "F"))
        out += [(m, "H", "all"), (m, "A", "all")]  # A on all: check against the stored frozen evaluation
    return out


def evaluate(workers: int = 7) -> None:
    from concurrent.futures import ProcessPoolExecutor

    from scahi.dota import final as F

    F._cpu_slot()
    (OUT / "eval").mkdir(parents=True, exist_ok=True)
    js = sorted(jobs(), key=lambda j: (j[1] not in ("RG", "H"), j[2] != "all"))  # expensive first
    with ProcessPoolExecutor(workers) as ex:
        for k in ex.map(_eval_job, js):
            print("done", k, flush=True)


SIZE_SETS = {"fine": (0, 8, 16, 32, 64, 128, 256, np.inf), "gt128": (0, 128, np.inf)}
SIZE_NAMES = {"fine": ("<8", "8-16", "16-32", "32-64", "64-128", "128-256", ">256"), "gt128": ("<=128", ">128")}


def _size_job(job: tuple[str, str, str]) -> str:
    """Per size bin (sigma = sqrt(w h) of the GT; bins as the DOTA evaluation, 128+ split): AP50, AP@[.5:.95], recall@0.5
    with bootstrap vectors (same resample weights as the row evaluation of the set)."""
    import torch

    from scahi.dota import boot_vec as BV
    from scahi.dota import evaluate as EV
    from scahi.dota import pipeline as P
    from scahi.eval.bootstrap import resample_weights

    torch.set_num_threads(1)
    m, name, st = job
    f = OUT / "sizes" / f"{name}_{m}_{st}.json"
    if f.exists():
        return f.stem
    stems = _subset(m) if st == "F" else P.split_stems("val")
    d = _dets(m, name)
    d = d[d.image.isin(set(stems))].reset_index(drop=True)
    W = resample_weights(len(stems))
    gt = EV.gt_arrays("val", stems)
    pts, vec = {}, {}
    for key, edges in SIZE_SETS.items():
        with mock.patch.object(EV, "SIZE_EDGES", edges):
            c = EV.build(gt, d, None, sizes=True)
        n = len(c.stems)
        for k, lbl in enumerate(SIZE_NAMES[key]):
            if lbl == "<=128":
                continue
            ap50 = BV._mean_rows([BV.class_ap_b(c, cl, 0, k, W) for cl in c.classes])
            ap = BV.ap_coco_b(c, W, bk=k)
            tp, npos = np.zeros(n), np.zeros(n)
            for cl in c.classes:
                s_, ix = c.dets[(cl, 0, k)]
                tp += np.bincount(ix[s_ == 1], minlength=n)
                npos += c.npos[(cl, k)]
            rec = np.array([100 * (tp @ w) / max(npos @ w, 1) for w in W])
            one = np.ones(n)
            pts[lbl] = {"AP50": EV._mean([EV.class_ap(c, cl, 0, k) for cl in c.classes]),
                        "AP": EV.ap_coco(c, bk=k), "R50": float(100 * (tp @ one) / max(npos @ one, 1)),
                        "n_gt": int(npos.sum())}
            vec[f"{lbl}|AP50"], vec[f"{lbl}|AP"], vec[f"{lbl}|R50"] = ap50, ap, rec
        del c
    np.savez(OUT / "sizes" / f"{f.stem}_boot.npz", **vec)
    f.write_text(json.dumps({"n_images": len(stems), "bins": pts}, indent=1))
    return f.stem


def size_jobs() -> list[tuple[str, str, str]]:
    return [(m, n, "F") for m in MODELS for n in ("N_z1", "RG", "A", "NMS-o2m")] + \
           [(m, n, "all") for m in MODELS for n in ("H", "RG", "A")]


def evaluate_sizes(workers: int = 7) -> None:
    from concurrent.futures import ProcessPoolExecutor

    from scahi.dota import final as F

    F._cpu_slot()
    (OUT / "sizes").mkdir(parents=True, exist_ok=True)
    js = sorted(size_jobs(), key=lambda j: (j[1] not in ("RG", "H"), j[2] != "all"))
    with ProcessPoolExecutor(workers) as ex:
        for k in ex.map(_size_job, js):
            print("done", k, flush=True)


KEYS = ("mAP50", "AP", "R50_crowd", "R50_iso")


def _con(va: dict, vb: dict, pa: dict, pb: dict, k: str) -> dict:
    d = va[k] - vb[k]
    return {"a": pa[k], "b": pb[k], "delta": pa[k] - pb[k],
            "ci95": [float(np.percentile(d, 2.5)), float(np.percentile(d, 97.5))]}


def counts() -> dict:
    """Object counts of the subsets (needs the DOTA-val labels) -> object_counts.json, an input of ``report``."""
    from scahi.dota import data as D

    ann = D.load("val")
    out = {}
    for m in MODELS:
        fit = _subset(m)
        out[m] = {"objects": sum(len(ann[s].cls) for s in fit),
                  "objects_non_difficult": int(sum((~ann[s].difficult).sum() for s in fit)),
                  "objects_total": sum(len(a.cls) for a in ann.values()),
                  "objects_non_difficult_total": int(sum((~a.difficult).sum() for a in ann.values()))}
    (OUT / "object_counts.json").write_text(json.dumps(out, indent=1))
    return out


def analyse() -> dict:
    """Contrasts from the evaluation artefacts (research repo) -> runs/dota/native_pass/report.json, then ``render``."""
    from scahi.dota import final as F
    from scahi.dota import pipeline as P

    cnt = json.loads((OUT / "object_counts.json").read_text())
    res: dict = {"framing": "docs/DECISIONS.md 2026-11-13 06:22 (exploratory, post hoc, descriptive; no verdict)",
                 "bootstrap": {"n": 1000, "seed": 0, "ci": "percentile 2.5/97.5, paired over the images of the set"},
                 "models": {}}
    for m in MODELS:
        meta = json.loads((OUT / f"N_z1_{m}.json").read_text())
        per = meta["images"]
        fit = _subset(m)
        fail = [s for s in P.split_stems("val") if not per[s]["fits"]]
        ld = lambda n, st: (json.loads((OUT / "eval" / f"{n}_{m}_{st}.json").read_text()),  # noqa: E731
                            dict(np.load(OUT / "eval" / f"{n}_{m}_{st}_boot.npz")))
        stored = lambda rid: (json.loads((F.VAL_DIR / "eval" / f"{rid}.json").read_text()),  # noqa: E731
                              dict(np.load(F.VAL_DIR / "eval" / f"{rid}_boot.npz")))
        names = ["N_z1", "A", "NMS-o2m", "RG"] + (["NMS-o2o"] if m == "yolov10s" else [])
        E = {n: ld(n, "F") for n in names}
        a_all, a_chk = stored(f"A_{m}_{S}"), ld("A", "all")
        check = {k: [a_all[0][k], a_chk[0][k]] for k in KEYS}
        assert all(abs(x - y) < 1e-9 for x, y in check.values()), check
        assert all(np.array_equal(a_all[1][k], a_chk[1][k]) for k in KEYS)
        rg_all, h_all = stored(f"RG_{m}_{S}"), ld("H", "all")
        ms = [per[s]["ms"] for s in fit]
        mem = [per[s]["peak_mem_mb"] for s in fit]
        r = {"subset_F": {"images": len(fit), "of": len(per), **cnt[m]},
             "failing_images": {s: {k: per[s][k] for k in ("W", "H", "input_hw", "error")} for s in fail},
             "runtime_ms": {"mean": float(np.mean(ms)), "median": float(np.median(ms)), "p95": float(np.percentile(ms, 95)),
                            "max": float(np.max(ms))},
             "peak_mem_mb": {"median": float(np.median(mem)), "max": float(np.max(mem))},
             "images_at_limit": sum(bool(per[s].get("at_limit")) for s in fit),
             "check_A_all_equals_frozen_eval": check,
             "points_F": {n: {k: E[n][0][k] for k in KEYS} for n in names},
             "contrasts_F": {f"N_z1 − {n}": {k: _con(E["N_z1"][1], E[n][1], E["N_z1"][0], E[n][0], k) for k in KEYS}
                             for n in names[1:]},
             "points_all": {"H": {k: h_all[0][k] for k in KEYS}, "RG": {k: rg_all[0][k] for k in KEYS},
                            "A": {k: a_all[0][k] for k in KEYS}},
             "contrasts_all": {f"H − {n}": {k: _con(h_all[1], v[1], h_all[0], v[0], k) for k in KEYS}
                               for n, v in (("RG", rg_all), ("A", a_all))}}
        sz = lambda n, st: (json.loads((OUT / "sizes" / f"{n}_{m}_{st}.json").read_text())["bins"],  # noqa: E731
                            dict(np.load(OUT / "sizes" / f"{n}_{m}_{st}_boot.npz")))
        SB = {(n, "F"): sz(n, "F") for n in ("N_z1", "RG", "A", "NMS-o2m")} | {(n, "all"): sz(n, "all") for n in ("H", "RG", "A")}
        bins = list(SB[("N_z1", "F")][0])
        r["size_points"] = {f"{n}|{st}": SB[(n, st)][0] for n, st in SB}
        r["size_contrasts"] = {}
        for (a_, b_, st) in (("N_z1", "RG", "F"), ("N_z1", "A", "F"), ("N_z1", "NMS-o2m", "F"), ("H", "RG", "all"), ("H", "A", "all")):
            (pa, va), (pb, vb) = SB[(a_, st)], SB[(b_, st)]
            r["size_contrasts"][f"{st}: {a_} − {b_}"] = {
                lbl: {k: {"a": pa[lbl][k], "b": pb[lbl][k], "delta": pa[lbl][k] - pb[lbl][k],
                           "ci95": [float(np.nanpercentile(va[f"{lbl}|{k}"] - vb[f"{lbl}|{k}"], 2.5)),
                                    float(np.nanpercentile(va[f"{lbl}|{k}"] - vb[f"{lbl}|{k}"], 97.5))]}
                      for k in ("AP50", "AP", "R50")} | {"n_gt": pa[lbl]["n_gt"]} for lbl in bins}
        res["models"][m] = r
    (OUT / "report.json").write_text(json.dumps(res, indent=1))
    return render(res)


def report() -> dict:
    """Report mode (regeneration, no data): runs/dota/native_pass/report.json -> REPORT.md and the reports/dota copies."""
    return render(json.loads((OUT / "report.json").read_text()))


def render(res: dict) -> dict:
    REP.mkdir(parents=True, exist_ok=True)
    (REP / "native_pass_exploratory.json").write_text(json.dumps(res, indent=1))
    L = ["# Native whole-image single pass on DOTA (exploratory, post hoc)", "",
         f"Framing: {res['framing']}. DOTA-val, devkit mAP50 without cap, AP@[.5:.95], recall@0.5 crowded / isolated "
         "GT; paired image bootstrap (1000, seed 0), 95 % percentile CI. Not for paper tables without the authors' decision.", ""]
    for m, r in res["models"].items():
        f = r["subset_F"]
        L += [f"## {m} (2048 weights)", "",
              f"Subset F: {f['images']} / {f['of']} images, {f['objects']} / {f['objects_total']} objects "
              f"({f['objects_non_difficult']} / {f['objects_non_difficult_total']} non-difficult). Native pass: "
              f"{r['runtime_ms']['mean']:.0f} ms mean, {r['runtime_ms']['median']:.0f} median, {r['runtime_ms']['max']:.0f} max per image; "
              f"peak memory {r['peak_mem_mb']['median'] / 1024:.2f} GB median, {r['peak_mem_mb']['max'] / 1024:.1f} GB max; "
              f"images at the pipeline limit: {r['images_at_limit']}.",
              "Failing images (OOM): " + (", ".join(f"{s} ({v['W']}x{v['H']})" for s, v in r["failing_images"].items()) or "none"), "",
              "| set | row | mAP50 | AP | R50 crowded | R50 isolated |", "|---|---|---|---|---|---|"]
        for n, p in r["points_F"].items():
            L.append(f"| F | {n} | " + " | ".join(f"{p[k]:.2f}" for k in KEYS) + " |")
        for n, p in r["points_all"].items():
            L.append(f"| all | {n} | " + " | ".join(f"{p[k]:.2f}" for k in KEYS) + " |")
        L += ["", "| contrast | Δ mAP50 [95 % CI] | Δ AP | Δ R50 crowded | Δ R50 isolated |", "|---|---|---|---|---|"]
        for nm, c in {**{f"F: {k}": v for k, v in r["contrasts_F"].items()},
                      **{f"all: {k}": v for k, v in r["contrasts_all"].items()}}.items():
            L.append(f"| {nm} | " + " | ".join(f"{c[k]['delta']:+.2f} [{c[k]['ci95'][0]:+.2f}, {c[k]['ci95'][1]:+.2f}]"
                                                for k in KEYS) + " |")
        L.append("")
        for nm, cs in r["size_contrasts"].items():
            L += [f"Size bins (sigma = sqrt(w h) of the GT), {nm}:", "",
                  "| bin | GT | AP50 a / b | Δ AP50 [95 % CI] | Δ AP [95 % CI] | R50 a / b | Δ R50 [95 % CI] |",
                  "|---|---|---|---|---|---|---|"]
            for lbl, c in cs.items():
                f_ = lambda k: f"{c[k]['delta']:+.2f} [{c[k]['ci95'][0]:+.2f}, {c[k]['ci95'][1]:+.2f}]"  # noqa: E731
                L.append(f"| {lbl} | {c['n_gt']} | {c['AP50']['a']:.1f} / {c['AP50']['b']:.1f} | {f_('AP50')} | {f_('AP')} | "
                         f"{c['R50']['a']:.1f} / {c['R50']['b']:.1f} | {f_('R50')} |")
            L.append("")
    (OUT / "REPORT.md").write_text("\n".join(L))
    (REP / "NATIVE_PASS_EXPLORATORY.md").write_text("\n".join(L))
    print("\n".join(L))
    return res


