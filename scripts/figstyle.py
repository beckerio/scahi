"""Central figure style of the project (matplotlib figures and the TikZ method figure).

Colours, fonts, sizes and resolutions live only here. ``apply()`` sets matplotlib's rcParams; ``write_tex()`` writes the
same colours as ``\\definecolor`` lines for the TikZ figure (``reports/figures/paper/tex/figstyle.tex``);
``figure_data()`` extracts the plotted values of a matplotlib figure so that every figure can be restyled from the JSON
next to it without re-running anything.

Palette (dataviz method, light paper surface): categorical slots in fixed order blue, orange, aqua (validated all-pairs;
aqua below 3:1 contrast -> always direct-labelled), sequential = blue ramp, text in ink colours only.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

import numpy as np

# ---- colours ---------------------------------------------------------------------------------------------------
INK, INK2, MUTED, GRID, SURF = "#0b0b0b", "#52514e", "#8a8984", "#e3e2dc", "#ffffff"
PANEL = "#f6f6f3"
BLUE, ORANGE, AQUA = "#2a78d6", "#eb6834", "#1baf7a"  # categorical slots 1-3 (fixed order)
BLUE_L, BLUE_M, BLUE_D, ORANGE_L = "#cde2fb", "#86b6ef", "#184f95", "#fbe1d6"
SEQ = ["#cde2fb", "#9ec5f4", "#6da7ec", "#3987e5", "#256abf", "#184f95", "#0d366b"]  # sequential blue ramp
ORD4 = ["#86b6ef", "#3987e5", "#1c5cab", "#0d366b"]  # ordinal blue ramp (step 250 .. 700)

# ---- fonts and sizes -------------------------------------------------------------------------------------------
FONT = "Inter"
MATH_FONT = "Fira Math"
FONT_SIZE, TITLE_SIZE, TICK_SIZE, LEGEND_SIZE = 7.5, 8.0, 7.0, 6.8
COL_W, FULL_W = 3.35, 6.9  # inches (two-column paper format: column / text width)
LINE_W, MARKER_SIZE = 1.6, 4.2

# ---- output ----------------------------------------------------------------------------------------------------
DPI_PNG = 220  # PNG next to every vector PDF
DPI_TIKZ_PNG = 220  # PNG rendering of the TikZ figure

TEX_COLOURS = {"ink": INK, "ink2": INK2, "muted": MUTED, "grid": GRID, "blue": BLUE, "bluel": BLUE_L, "bluem": BLUE_M,
               "blued": BLUE_D, "orange": ORANGE, "orangel": ORANGE_L, "aqua": AQUA, "panel": PANEL}


def apply() -> None:
    import matplotlib.pyplot as plt
    from matplotlib import font_manager

    for f in font_manager.findSystemFonts():
        if FONT in Path(f).name:
            font_manager.fontManager.addfont(f)
    plt.rcParams.update({
        "font.family": FONT, "font.size": FONT_SIZE, "axes.titlesize": TITLE_SIZE, "axes.labelsize": FONT_SIZE,
        "xtick.labelsize": TICK_SIZE, "ytick.labelsize": TICK_SIZE, "legend.fontsize": LEGEND_SIZE,
        "axes.edgecolor": MUTED, "axes.labelcolor": INK, "text.color": INK, "xtick.color": INK2, "ytick.color": INK2,
        "axes.grid": True, "grid.color": GRID, "grid.linewidth": 0.5, "axes.spines.top": False,
        "axes.spines.right": False, "axes.linewidth": 0.6, "lines.linewidth": LINE_W, "lines.markersize": MARKER_SIZE,
        "pdf.fonttype": 42, "ps.fonttype": 42, "savefig.dpi": 300, "figure.facecolor": SURF, "axes.facecolor": SURF,
        "legend.frameon": False, "axes.titleweight": "semibold", "axes.titlelocation": "left",
    })


def write_tex(path: Path) -> None:
    lines = ["% generated by scripts/figstyle.py - do not edit (colours of the matplotlib figures)"]
    lines += [f"\\definecolor{{{k}}}{{HTML}}{{{v.lstrip('#').upper()}}}" for k, v in TEX_COLOURS.items()]
    path.write_text("\n".join(lines) + "\n")


# ---- data next to each figure ----------------------------------------------------------------------------------

MAX_ARRAY = 250_000  # images/heatmaps with more values are stored as shape + extent only


def _num(a: Any) -> Any:
    a = np.asarray(a, dtype=float) if not np.ma.isMaskedArray(a) else np.ma.filled(np.asarray(a, dtype=float), np.nan)
    a = np.round(a, 5)
    return [None if not np.isfinite(v) else float(v) for v in a.ravel()] if a.ndim <= 1 else \
        [[None if not np.isfinite(v) else float(v) for v in row] for row in a.reshape(a.shape[0], -1)]


def _hex(c: Any) -> Any:
    from matplotlib.colors import to_hex

    try:
        return to_hex(c, keep_alpha=False)
    except (ValueError, TypeError):
        return None


def figure_data(fig, sources: list[str], extra: dict[str, Any] | None = None) -> dict[str, Any]:
    """Plotted values per axes: lines, scatter/line collections, bars, images (small ones in full), texts, axes setup."""
    from matplotlib.collections import LineCollection, PathCollection, PolyCollection
    from matplotlib.image import AxesImage
    from matplotlib.patches import Rectangle

    out: dict[str, Any] = {"sources": sorted(set(sources)), "axes": []}
    for ax in fig.axes:
        a: dict[str, Any] = {"title": ax.get_title(loc="left") or ax.get_title(), "xlabel": ax.get_xlabel(),
                             "ylabel": ax.get_ylabel(), "xscale": ax.get_xscale(), "yscale": ax.get_yscale(),
                             "xlim": _num(ax.get_xlim()), "ylim": _num(ax.get_ylim()),
                             "xticks": _num(ax.get_xticks()), "xticklabels": [t.get_text() for t in ax.get_xticklabels()],
                             "yticks": _num(ax.get_yticks()), "yticklabels": [t.get_text() for t in ax.get_yticklabels()],
                             "lines": [], "scatter": [], "segments": [], "areas": [], "bars": [], "images": [], "texts": []}
        for ln in ax.get_lines():
            a["lines"].append({"label": ln.get_label(), "color": _hex(ln.get_color()), "linestyle": str(ln.get_linestyle()),
                               "marker": str(ln.get_marker()), "x": _num(ln.get_xdata()), "y": _num(ln.get_ydata())})
        for c in ax.collections:
            if isinstance(c, PathCollection):
                off = c.get_offsets()
                fc = c.get_facecolors()
                a["scatter"].append({"label": c.get_label(), "x": _num(off[:, 0]) if len(off) else [],
                                     "y": _num(off[:, 1]) if len(off) else [],
                                     "facecolor": _hex(fc[0]) if len(fc) else None,
                                     "edgecolor": _hex(c.get_edgecolors()[0]) if len(c.get_edgecolors()) else None,
                                     "values": _num(c.get_array()) if c.get_array() is not None else None})
            elif isinstance(c, LineCollection):
                a["segments"].append({"label": c.get_label(), "segments": [_num(s) for s in c.get_segments()],
                                      "color": _hex(c.get_colors()[0]) if len(c.get_colors()) else None})
            elif isinstance(c, PolyCollection):
                a["areas"].append({"label": c.get_label(), "paths": [_num(p.vertices) for p in c.get_paths()],
                                   "color": _hex(c.get_facecolors()[0]) if len(c.get_facecolors()) else None})
        for p in ax.patches:
            if isinstance(p, Rectangle):
                a["bars"].append({"label": p.get_label(), "x": float(p.get_x()), "y": float(p.get_y()),
                                  "w": float(p.get_width()), "h": float(p.get_height()), "color": _hex(p.get_facecolor())})
        for im in ax.get_images():
            if isinstance(im, AxesImage):
                arr = np.asarray(im.get_array())
                rec = {"shape": list(arr.shape), "extent": _num(im.get_extent()), "cmap": im.get_cmap().name,
                       "clim": _num(im.get_clim())}
                if arr.ndim == 2 and arr.size <= MAX_ARRAY:
                    rec["values"] = _num(arr)
                elif arr.ndim == 3:
                    rec["note"] = "photo (RGB) - see sources / extra for the image and crop"
                a["images"].append(rec)
        for t in ax.texts:
            a["texts"].append({"text": t.get_text(), "xy": _num(getattr(t, "xy", t.get_position()))})
        out["axes"].append(a)
    if extra:
        out["extra"] = extra
    return out
