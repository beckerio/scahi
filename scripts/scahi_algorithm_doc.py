         "## 2. Prediction table (per image, per stack)", "",
         "For every cached anchor of every pass with **p_max = max_c p_c ≥ tau_splat**: centre (cx, cy), width and "
         "height w, h = max(x2 − x1, 1e-3), max(y2 − y1, 1e-3), size **σ = √(w·h)** (original px), log w, log h, class "
         "vector p ∈ [0, 1]^nc, pass id, level index k.", "",
         "## 3. Weights (F2)", "",
         "**Border taper b** of a prediction in tile t of level k, evaluated at its centre (cx, cy):",
