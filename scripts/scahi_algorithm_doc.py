         "| tau_peak | τ_p | minimum field value of a peak (Section 6) |",
         "| cell_factor | κ | spatial cell side g_j = max(1, σ_j / κ) |",
         "| bins_per_oct | β | σ bins per octave |",
         "| iou_cluster | – | member clustering threshold (fixed 0.5) |",
         "| overlap | ρ | tile overlap and taper width (fixed 0.3) |", "",
         "**Pre-specified setting (F2):** calib grid "
         f"tau_splat × tau_peak × cell_factor × bins_per_oct = "
         f"{sorted({g['tau_splat'] for g in f2grid})} × {sorted({g['tau_peak'] for g in f2grid})} × "
