         "configurations. Notation: image W × H px (original), one *stack* = a set of *levels*, a level = one or more "
         "*passes* (whole image or tiles). All coordinates are original-image px.", "",
         "## 1. Passes and inputs", "",
         "**Levels used in the paper.** A stack is `(whole-image pass at long side s, tiles at zoom z = 2 with network "
