def _whole_px(lv: str) -> str:
    """Long side of the whole-image pass of a level key (w2048 -> 2048, w1.0 -> 1920 on VisDrone)."""
    z = lv[1:]
    return z if float(z) > 10 else f"{round(float(z) * 1920)}"


def supplement_rows(fin: list, ext: list, dota: list) -> list[tuple]:
    """(dataset, detector, s, setting, passes, head, params, code row) for every frozen SCAHI row, in paper terms."""
    out = []
    main = {"D-1280": "1280", "D-1536": "1536", "D-T4": "– (scale-norm. training)", "X2": "2048", "X4": "1536"}
    for r in fin:
        inf = r.get("inference") or {}
        if inf.get("fusion") != "F2":
            continue
        lv, sz = inf["levels"], main.get(r["id"], "–")
        pas = "whole image + tiles" if _whole_px(lv[0]) == sz else f"whole image at {_whole_px(lv[0])} px + tiles"
        out.append(("VisDrone", "YOLOv10s (main study)", sz, "pre-specified", pas, inf["branch"], inf["params"], r["id"]))
    for r in ext:
        if r["kind"] != "cache" or r["fusion"]["variant"] != "F2":
            continue
        rid, lv = r["id"], r["fusion"]["levels"]
        if rid.startswith("XG_"):
            m, sz = rid.split("_")[1:3]
            setting = "refined grid (post hoc)"
        else:
            m = rid.split("_")[1]
            sz = "".join(ch for ch in rid.split("_")[2] if ch.isdigit())
            setting = "pre-specified"
        out.append(("VisDrone", MODEL.get(m, m), sz, setting, "whole image" if len(lv) == 1 else "whole image + tiles",
                    r["fusion"]["branch"], r["fusion"]["params"], rid))
    for r in dota:
        if r.get("variant") != "F2" or r.get("kind") != "cache":
            continue
        setting = "refined grid (pre-specified on DOTA)" if r["row"] in ("RG", "B-RG") else "pre-specified"
        out.append(("DOTA v1.5", MODEL.get(r["model"], r["model"]), str(r["s"]), setting,
                    "whole image" if r["stack"] == "B" else "whole image + tiles", r["branch"], r["cfg"], r["id"]))
    order, mo = {"VisDrone": 0, "DOTA v1.5": 1}, list(MODEL.values())
    return sorted(out, key=lambda x: (order[x[0]], mo.index(x[1].split(" ")[0]), "main" in x[1], x[2], x[3], x[4], x[5]))


